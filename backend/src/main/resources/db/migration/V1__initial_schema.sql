CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(50)   NOT NULL,
    name            VARCHAR(200)  NOT NULL,
    description     VARCHAR(1000),
    unit            VARCHAR(20)   NOT NULL,
    weight_kg       NUMERIC(10, 3),
    min_stock_level INT           NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT ck_products_min_stock CHECK (min_stock_level >= 0)
);

CREATE TABLE storage_locations (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(30) NOT NULL,
    zone     VARCHAR(20) NOT NULL,
    aisle    VARCHAR(10) NOT NULL,
    rack     INT         NOT NULL,
    shelf    INT         NOT NULL,
    capacity INT         NOT NULL,
    active   BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_locations_code UNIQUE (code),
    CONSTRAINT ck_locations_capacity CHECK (capacity > 0),
    CONSTRAINT ck_locations_position CHECK (rack > 0 AND shelf > 0)
);

-- How many units of a product sit in a location (one row per product+location pair)
CREATE TABLE stock_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES products (id),
    location_id BIGINT NOT NULL REFERENCES storage_locations (id),
    quantity    INT    NOT NULL,
    version     BIGINT NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_stock_product_location UNIQUE (product_id, location_id),
    CONSTRAINT ck_stock_quantity CHECK (quantity >= 0)
);
CREATE INDEX ix_stock_items_location ON stock_items (location_id);

-- Immutable audit trail of every stock change
CREATE TABLE stock_movements (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT       NOT NULL REFERENCES products (id),
    from_location_id BIGINT       REFERENCES storage_locations (id),
    to_location_id   BIGINT       REFERENCES storage_locations (id),
    quantity         INT          NOT NULL,
    type             VARCHAR(20)  NOT NULL,
    reference        VARCHAR(100),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_movements_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_movements_product ON stock_movements (product_id);
CREATE INDEX ix_movements_created ON stock_movements (created_at);

CREATE TABLE customer_orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number  VARCHAR(30)  NOT NULL,
    customer_name VARCHAR(200) NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    picked_at     TIMESTAMP WITH TIME ZONE,
    shipped_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_orders_number UNIQUE (order_number)
);
CREATE INDEX ix_orders_status ON customer_orders (status);

CREATE TABLE order_lines (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES customer_orders (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products (id),
    quantity   INT    NOT NULL,
    CONSTRAINT uq_order_line_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0)
);

CREATE SEQUENCE order_number_seq START WITH 1001;
